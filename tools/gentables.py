#!/usr/bin/env python3
"""gentables: generate driver/src/mxtables.inc (MXDRV tables used by mxcore.s) and
driver/src/adpcmtab.inc (MSM6258 ADPCM magnitudes used by the loader, mxload.s)."""
import sys

KC_NOTE = [0, 1, 2, 4, 5, 6, 8, 9, 10, 12, 13, 14]
PCMVOL = [0x0f, 0x0f, 0x0f, 0x0e, 0x0e, 0x0e, 0x0d, 0x0d, 0x0d, 0x0c, 0x0c, 0x0b, 0x0b, 0x0b, 0x0a, 0x0a,
          0x0a, 0x09, 0x09, 0x08, 0x08, 0x08, 0x07, 0x07, 0x07, 0x06, 0x06, 0x05, 0x05, 0x05, 0x04, 0x04,
          0x04, 0x03, 0x03, 0x02, 0x02, 0x02, 0x01, 0x01, 0x01, 0x00, 0x00, 0xff]


def rows(vals):
    return ['        .byte ' + ','.join('$%02X' % v for v in vals[i:i + 16]) for i in range(0, len(vals), 16)]


def main():
    idx = {n: i for i, n in enumerate(KC_NOTE)}
    L = ['; mxtables.inc - generated by tools/gentables.py. Do not edit by hand.',
         'keycode:                ; L000d24: note index (0..95) -> OPM KC']
    L += rows([((i // 12) << 4) | KC_NOTE[i % 12] for i in range(96)])
    L.append('kcidx:                  ; OPM KC (0..127) -> note index (unused codes -> the note below)')
    inv = []
    for k in range(128):
        o, n = k >> 4, k & 15
        if n not in idx:
            n -= 1
        inv.append(o * 12 + idx[n])
    L += rows(inv)
    L.append('carrier:                ; L000df6: CON -> carrier slot mask')
    L.append('        .byte $08,$08,$08,$08,$0C,$0E,$0E,$0F')
    L.append('voltab:                 ; L000e56: @v-less volume 0..15 -> attenuation')
    L.append('        .byte $2A,$28,$25,$22,$20,$1D,$1A,$18,$15,$12,$10,$0D,$0A,$08,$05,$02')
    L.append('pcmvol:                 ; PCMVolume: attenuation 0..$2A -> PCM8 volume')
    L += rows(PCMVOL)
    L.append('bitlo:                  ; channel -> mask bit (low byte)')
    L.append('        .byte ' + ','.join('$%02X' % ((1 << c) & 0xFF) for c in range(16)))
    L.append('bithi:')
    L.append('        .byte ' + ','.join('$%02X' % (((1 << c) >> 8) & 0xFF) for c in range(16)))
    L.append('stubtab:                ; L0019b2: sequence of an ended channel (rest 128, end)')
    L.append('        .byte $7F,$F1,$00')
    out = sys.argv[1] if len(sys.argv) > 1 else 'driver/src/mxtables.inc'
    open(out, 'w').write('\n'.join(L) + '\n')


DLT = [16, 17, 19, 21, 23, 25, 28, 31, 34, 37, 41, 45, 50, 55, 60, 66,
       73, 80, 88, 97, 107, 118, 130, 143, 157, 173, 190, 209, 230, 253, 279, 307,
       337, 371, 408, 449, 494, 544, 598, 658, 724, 796, 876, 963, 1060, 1166, 1282, 1411, 1552]


def adpcm(out='driver/src/adpcmtab.inc'):
    """mag[scale][m] = (m&4 ? d) + (m&2 ? d>>1) + (m&1 ? d>>2) + (d>>3), d = DLT[scale];
    index (scale & 31) << 3 | m in page 0 (scale < 32) or page 1 (scale >= 32)."""
    mag = [[((m >> 2) & 1) * d + ((m >> 1) & 1) * (d >> 1) + (m & 1) * (d >> 2) + (d >> 3)
            for m in range(8)] for d in DLT]
    p0 = [v for s in mag[:32] for v in s]
    p1 = [v for s in mag[32:] for v in s]
    L = ['; adpcmtab.inc - generated by tools/gentables.py. Do not edit by hand.']
    for name, vals in (('mag0l', [v & 255 for v in p0]), ('mag0h', [v >> 8 for v in p0]),
                       ('mag1l', [v & 255 for v in p1]), ('mag1h', [v >> 8 for v in p1])):
        L.append(name + ':')
        L += rows(vals)
    open(out, 'w').write('\n'.join(L) + '\n')


if __name__ == '__main__':
    adpcm()
    main()
